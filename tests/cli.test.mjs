import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createApp } from '../server/index.mjs';
import { outlinePdf } from './fixtures/outline-pdf.mjs';

test('subscription CLI preserves version identity, separate notes/activities, and question context without a provider', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'pw-cli-'));
  const app = await createApp({dataDir: directory, download: async url => ({url, contentType: 'text/html', buffer: Buffer.from('<html><head><title>Evidence study</title></head><body><main><h1>Evidence study</h1><p>This study compares two approaches using a controlled evaluation. Its evidence is limited to a single dataset. Further experiments are needed to establish broader applicability.</p></main></body></html>')})});
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(directory, {recursive:true,force:true}); });
  const env = {...process.env, PAPER_WORKBENCH_API_KEY: '', PAPER_WORKBENCH_URL: `http://127.0.0.1:${server.address().port}`};
  async function cli(args, body) {
    return await new Promise((resolve,reject) => {
      const process = spawn(env.NODE || 'node', ['scripts/paper-workbench.mjs', ...args], {env, stdio:['pipe','pipe','pipe']});
      let out = '', err = '';
      process.stdout.on('data', chunk => out += chunk); process.stderr.on('data', chunk => err += chunk);
      process.once('error', reject);
      process.once('close', code => code ? reject(new Error(err || `exit ${code}`)) : resolve(JSON.parse(out)));
      process.stdin.end(body === undefined ? undefined : JSON.stringify(body));
    });
  }
  const {paper} = await cli(['import','https://example.com/study']);
  const published = await cli(['publish',paper.id,'-'], {source:{agent:'CLI integration fixture'}, style:'critical', focus:'Limits of evidence', summary:{language:'en',markdown:'## Evidence boundary\nThe source studies a single dataset. [p.1]'}});
  const id = published.paper.activeReadingId;
  assert.equal(published.paper.readingVersions.find(v => v.id===id).style,'critical');
  await cli(['publish',paper.id,'-'],{source:{agent:'CLI integration fixture'},translations:[{target:'reading',readingId:id,language:'zh-CN',markdown:'## 证据边界\n原文只研究了一个数据集。 [p.1]'}]});
  const versions = await cli(['readings',paper.id]);
  assert.equal(versions.readingVersions.length,1);
  assert.match(versions.readingVersions[0].translations['zh-CN'].markdown,/证据边界/);
  const primary = await cli(['source',paper.id]);
  assert.match(primary.text, /single dataset/);
  assert.equal(primary.readingVersions, undefined);
  assert.equal(primary.summary, undefined);
  assert.equal(primary.translations, undefined);
  const withDerived = await cli(['source',paper.id,'--include-derived']);
  assert.equal(withDerived.activeReadingId, id);
  assert.equal(withDerived.readingVersions.length, 1);
  await assert.rejects(cli(['source',paper.id,'--pages','9007199254740992']), /Invalid page range/);
  await assert.rejects(cli(['source',paper.id,'--pages','1-0']), /Invalid page range/);
  const note = await cli(['note',paper.id,'-'],{kind:'note',page:1,quote:'single dataset',body:'Check external validity',tags:['limits']});
  assert.equal(note.annotation.kind,'note');
  const activityTask = {agentTaskId:'29e96487-b9d8-4374-89c8-f4226a1be301',sourceScope:'source-text',kind:'explanation',page:1,text:'single dataset',language:'en',result:'The evaluation does not establish results outside this dataset.',source:{agent:'CLI integration fixture'}};
  const activity = await cli(['activity',paper.id,'-'],activityTask);
  assert.equal(activity.activity.kind,'explanation');
  const repeatedActivity = await cli(['activity',paper.id,'-'],activityTask);
  assert.equal(repeatedActivity.reused,true);
  assert.deepEqual(repeatedActivity.activity,activity.activity);
  assert.deepEqual((await cli(['activities',paper.id,'--agent-task',activityTask.agentTaskId])).activities,[activity.activity]);
  assert.deepEqual((await cli(['activities',paper.id,'--agent-task','29e96487-b9d8-4374-89c8-f4226a1be302'])).activities,[]);
  await assert.rejects(cli(['activity',paper.id,'-'],{...activityTask,result:'A different response.'}),/HTTP 409/);
  await assert.rejects(cli(['activities',paper.id,'--agent-task','not-a-uuid']),/HTTP 400/);
  await assert.rejects(cli(['notes',paper.id,'--agent-task',activityTask.agentTaskId]),/not supported/);
  assert.equal((await cli(['notes',paper.id])).annotations.length,1);
  assert.equal((await cli(['sessions',paper.id])).conversations.length,0);
  const overviewSession = await cli(['new-session',paper.id,'--quote','A generated overview passage']);
  assert.deepEqual(overviewSession.conversation.metadata,{quote:'A generated overview passage'});
  const scoped = {quote:'A generated overview passage',sourceScope:'reading',readingId:id};
  const scopedSession = await cli(['new-session',paper.id,'--quote',scoped.quote,'--source-scope','reading','--reading',id]);
  assert.deepEqual(scopedSession.conversation.metadata,scoped);
  const emptyScopedSession = await cli(['conversation',paper.id,scopedSession.conversationId]);
  assert.deepEqual(emptyScopedSession.conversation.metadata,scoped);
  assert.deepEqual(emptyScopedSession.messages,[]);
  const questionTaskId='d9748cfb-4fd0-4fa2-b880-48f1a2967e72';
  await cli(['answer',paper.id,'-'],{conversationId:scopedSession.conversationId,agentTaskId:questionTaskId,source:{agent:'CLI integration fixture'},question:'Explain this generated interpretation.',answer:'Check its claims against the source.'});
  const importedQuestion=(await cli(['conversation',paper.id,scopedSession.conversationId])).messages;
  assert.deepEqual(importedQuestion[0].metadata,scoped);
  assert.deepEqual(importedQuestion.map(message=>message.agentTaskId),[questionTaskId,questionTaskId]);
  await assert.rejects(cli(['new-session',paper.id,'--quote','Wrong source','--source-scope','reading','--reading','missing-version']),/HTTP 404/);
  await assert.rejects(cli(['new-session',paper.id,'--quote','Wrong anchor','--source-scope','abstract','--page','1']),/HTTP 400/);
  await assert.rejects(cli(['new-session',paper.id,'--quote','Missing scope','--reading',id]),/HTTP 400/);
  const pageSession = await cli(['new-session',paper.id,'--page','1']);
  assert.deepEqual(pageSession.conversation.metadata,{page:1});
  const session = await cli(['new-session',paper.id,'--quote','single dataset','--page','1']);
  await cli(['answer',paper.id,'-'],{conversationId:session.conversationId,source:{agent:'CLI integration fixture'},question:'What needs replication?',answer:'Evaluate on additional datasets. [p.1]'});
  assert.equal((await cli(['sessions',paper.id])).conversations[0].messageCount,2);
  // The browser may switch active sessions while an external agent is reasoning.
  const later = await cli(['new-session',paper.id]);
  const messages = await cli(['conversation',paper.id,session.conversationId]);
  assert.equal(messages.conversationId,session.conversationId);
  assert.equal(messages.messages.length,2);
  assert.equal(messages.messages[0].content,'What needs replication?');
  assert.equal((await fetch(env.PAPER_WORKBENCH_URL+'/api/chats?paperId='+paper.id).then(r=>r.json())).conversationId,later.conversationId);
  await cli(['answer',paper.id,'-'],{conversationId:session.conversationId,source:{agent:'CLI integration fixture'},question:'Which session receives this?',answer:'The explicitly bound original session.'});
  assert.equal((await cli(['conversation',paper.id,session.conversationId])).messages.length,4);
  assert.equal((await cli(['conversation',paper.id,later.conversationId])).messages.length,0);
  const other = await cli(['import','https://example.com/other-study']);
  await assert.rejects(cli(['conversation',other.paper.id,session.conversationId]),/HTTP 404/);
  await assert.rejects(cli(['conversation',paper.id]),/Expected/);
  await assert.rejects(cli(['conversation',paper.id,'']),/nonempty/);

  // A real multipage PDF keeps all page text once; partial figures are explicit.
  const pdfPath = join(directory,'source.pdf');
  await writeFile(pdfPath,outlinePdf());
  const {paper:pdf} = await cli(['import',pdfPath]);
  const figures=[{id:'first',page:1,crop:{x:.1,y:.1,width:.7,height:.2},caption:'First fixture crop'},{id:'last',page:3,crop:{x:.1,y:.1,width:.7,height:.2},caption:'Last fixture crop'}];
  await cli(['publish',pdf.id,'-'],{source:{agent:'CLI integration fixture'},figures});
  const pdfFull=(await cli(['get',pdf.id])).paper;
  const source=await cli(['source',pdf.id]);
  assert.deepEqual(source.pages,pdfFull.pages);
  assert.equal(source.abstractIsExcerpt,Boolean(pdfFull.abstractIsExcerpt));
  assert.equal(source.text,undefined);
  assert.equal(source.figures.length,2);
  assert.equal(source.figuresPartial,undefined);
  const ranged=await cli(['source',pdf.id,'--pages','1']);
  assert.deepEqual(ranged.pages,[pdfFull.pages[0]]);
  assert.equal(ranged.text,undefined);
  assert.equal(ranged.figuresPartial,true);
  assert.deepEqual(ranged.figures.map(f=>f.id),['first']);
  assert.match(ranged.sourceNotice,/figure to save one reviewed crop/);
  assert.match(ranged.sourceNotice,/preserve unrelated entries/);
  const derived=await cli(['source',pdf.id,'--include-derived']);
  assert.equal(derived.text,pdfFull.text);
  const rangeDerived=await cli(['source',pdf.id,'--pages','1','--include-derived']);
  assert.equal(rangeDerived.text,'[p.1]\n'+pdfFull.pages[0].text);
  assert.equal(rangeDerived.figuresPartial,true);
  const pdfBundle=await cli(['export',pdf.id,'--out',join(directory,'pdf-bundle'),'--annotated-pdf']);
  assert.ok((await readFile(pdfBundle.annotatedPdf)).subarray(0,8).includes(Buffer.from('%PDF-')));
  assert.match(pdfBundle.annotationNotice,/saved annotations/);
  assert.deepEqual(await readFile(pdfBundle.pdf),outlinePdf());
  const archived=JSON.parse(await readFile(pdfBundle.source,'utf8'));
  assert.equal(archived.text,pdfFull.text);
  assert.deepEqual(archived.pages,pdfFull.pages);
  assert.equal(archived.figures.length,2);

  // Single-figure imports retain unrelated entries and fail stale revisions rather than rebasing silently.
  const collection = await cli(['figures',pdf.id]);
  const reviewed = {pdfRevision:collection.pdfRevision,expectedFiguresRevision:collection.figuresRevision,figure:{page:2,crop:{x:.1,y:.1,width:.7,height:.2},caption:'A verified second-page crop',label:'Figure 2'},source:{method:'manual',reviewed:true}};
  const added = await cli(['figure',pdf.id,'-'], reviewed);
  assert.equal(added.figures.length,3);
  assert.deepEqual(added.figures.slice(0,2).map(item=>item.id),['first','last']);
  await assert.rejects(cli(['figure',pdf.id,'-'],reviewed),/HTTP 409/);
  const changed = await cli(['figure',pdf.id,'-','--figure',added.figure.id],{...reviewed,expectedFiguresRevision:added.figuresRevision,figure:{caption:'Corrected source caption'}});
  assert.equal(changed.figure.id,added.figure.id);
  assert.equal(changed.figures.length,3);
  assert.equal(changed.figure.caption,'Corrected source caption');
  assert.deepEqual(changed.figure.crop,reviewed.figure.crop);
  await assert.rejects(cli(['figure',pdf.id,'-','--model','invalid'],reviewed),/not supported/);

  const bundle = await cli(['export',paper.id,'--out',join(directory,'bundle')]);
  const notes = JSON.parse(await readFile(bundle.annotations,'utf8'));
  assert.equal(notes.annotations[0].body,'Check external validity');
  assert.equal(JSON.parse(await readFile(bundle.source,'utf8')).activeReadingId,id);
  assert.equal(JSON.parse(await readFile(bundle.activities,'utf8')).activities.length,1);
  const timeoutSettings = await cli(['config','set','--request-timeout-seconds','240']);
  assert.equal(timeoutSettings.requestTimeoutSeconds,240);
  assert.equal((await cli(['config','show'])).requestTimeoutSeconds,240);
  await assert.rejects(cli(['config','set','--request-timeout-seconds','14']),/between 15 and 600/);
});
